const sourceTextNodes = [];
const textWalker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
while (textWalker.nextNode()) {
  const node = textWalker.currentNode;
  if (node.parentElement.closest("script, style")) continue;
  sourceTextNodes.push([node, node.nodeValue]);
}

function translateStatic(lang) {
  for (const [node, source] of sourceTextNodes) {
    const key = source.trim().replace(/\s+/g, " ");
    const translation = lang === "it" && staticItalian[key];
    node.nodeValue = translation
      ? source.match(/^\s*/)[0] + translation + source.match(/\s*$/)[0]
      : source;
  }
}
